/* Exports the affix database and the Easy Mode matrix from js/filter-engine.js.
   node tools/export-affix-db.mjs  ->  data/affix-db.json, data/affix-db.csv, data/easy-mode-matrix.md
   Source of truth stays AFF_SRC / EZ_ARCH in js/filter-engine.js. Nothing here touches the in-game code. */
import fs from "node:fs";
import * as E from "../js/filter-engine.js";
const out=new URL("../data/",import.meta.url);
const isIdol=a=>/^idol_/i.test(a.id)||a.tags.some(t=>/idol/i.test(t));
const archOf=new Map(),idolArch=new Map();
for(const a of E.EZ_ARCH){
  for(const id of a.ids){const t=E.LINEN[id];(archOf.get(id)||archOf.set(id,[]).get(id)).push(a.k);}
  for(const id of a.idol){(idolArch.get(id)||idolArch.set(id,[]).get(id)).push(a.k);}
}
/* named lines match by text, so a line also counts for every archetype that lists a line with the same text */
const byText=new Map();
for(const [id,ks] of archOf){const t=E.LINEN[id];if(!t)continue;const s=byText.get(t)||byText.set(t,new Set()).get(t);ks.forEach(k=>s.add(k));}
for(const [id,ks] of idolArch){const t=E.LINEN[id];if(!t)continue;const s=byText.get(t)||byText.set(t,new Set()).get(t);ks.forEach(k=>s.add(k));}
/* the size tiers of Idol lines are stored as IdolFireRes_s in the affix table and as idol_fire_res_s in the line list; same affix, so the text comes from the line list */
const idolKey=id=>/^Idol[A-Z]/.test(id)?id.replace(/([a-z0-9])([A-Z])/g,"$1_$2").toLowerCase():id;
const idolAlt=id=>{const k=idolKey(id);return[k,k.replace(/^idol_totem_/,"idol_ballista_"),k.replace(/^idol_(\w+?)_([smlx])$/,"idol_$1_damage_$2")];};
const textOf=id=>E.LINEN[id]||idolAlt(id).map(k=>E.LINEN[k]).find(Boolean)||"";
const excl=new Set(E.EZ_EXCLUDED),exclText=new Set([...excl].map(i=>E.LINEN[i]).filter(Boolean));
const rows=E.AFF.map(a=>{
  const t=textOf(a.id);
  const ks=[...(byText.get(t)||[])].sort();
  return{id:a.id,text:t,type:a.type==="P"?"Prefix":"Suffix",group:a.group,slots:a.tags,excludes:a.ex,weight:a.w,tiers:a.n,ilvl_top:a.hi,ilvl_low:a.lo,tier_ilvls:a.lv,
    idol:isIdol(a),excluded:exclText.has(t),switch_dependent:E.COND_LINE.has(a.id),style:E.EZ_ST[a.id]||"",easy_mode:ks};
});
const db={_doc:"Affix database of Oathfilter. Generated from js/filter-engine.js (AFF_SRC, EZ_ARCH). Data: local game files, build "+E.DATA_BUILD.build+" (read "+E.DATA_BUILD.read+"). Not official.",build:E.DATA_BUILD.build,count:rows.length,affixes:rows};
fs.writeFileSync(new URL("affix-db.json",out),JSON.stringify(db,null,1)+"\n");
const q=v=>'"'+String(v).replace(/"/g,'""')+'"';
const head=["id","text","type","group","slots","weight","tiers","ilvl_top","ilvl_low","idol","excluded","switch_dependent","style","easy_mode"];
fs.writeFileSync(new URL("affix-db.csv",out),[head.join(",")].concat(rows.map(r=>[r.id,r.text,r.type,r.group,r.slots.join(";"),r.weight,r.tiers,r.ilvl_top,r.ilvl_low,r.idol,r.excluded,r.switch_dependent,r.style,r.easy_mode.join(";")].map(q).join(","))).join("\n")+"\n");
/* matrix doc */
let md="# Oathfilter Easy Mode: which line sits where\n\nGenerated by `tools/export-affix-db.mjs` from the code (build "+E.DATA_BUILD.build+"). Named lines match by their text, so a gear line also covers every line with the same text (Idol lines, `_2h`, `ring_` variants).\n\n## Per group\n\n";
for(const a of E.EZ_ARCH){
  const gear=[...new Set(a.ids.map(i=>E.LINEN[i]||i))],idol=[...new Set(a.idol.map(i=>E.LINEN[i]||i))];
  md+="### "+a.n+" (`"+a.k+"`)\n- Gear: "+(gear.length?gear.join("; "):"none")+"\n- Idols: "+(idol.length?idol.join("; "):"none")+"\n\n";
}
md+="## Per line (gear, grouped by text)\n\n| Line | Ids | Groups | Slots | Tiers |\n|---|---|---|---|---|\n";
const g=new Map();
for(const r of rows.filter(r=>!r.idol)){const k=r.text||r.id;(g.get(k)||g.set(k,[]).get(k)).push(r);}
for(const [t,v] of [...g].sort((a,b)=>a[0].localeCompare(b[0]))){
  const ks=[...new Set(v.flatMap(r=>r.easy_mode))].sort();
  md+="| "+t+" | "+v.map(r=>r.id).join(", ")+" | "+(ks.length?ks.join(", "):v.some(r=>r.excluded)?"excluded":"**none**")+" | "+[...new Set(v.flatMap(r=>r.slots))].join(", ")+" | "+Math.max(...v.map(r=>r.tiers))+" |\n";
}
const none=[...g].filter(([t,v])=>!v.some(r=>r.easy_mode.length)&&!v.some(r=>r.excluded)).map(([t])=>t);
const exl=[...g].filter(([t,v])=>v.some(r=>r.excluded)).map(([t])=>t);
md+="\n## Not in any group ("+none.length+")\n\n"+(none.map(t=>"- "+t).join("\n")||"- none")+"\n\n## Deliberately excluded ("+exl.length+")\n\nThese lines are in no group on purpose (`excluded` in data/easy-mode-groups.json).\n\n"+exl.map(t=>"- "+t).join("\n")+"\n";
fs.writeFileSync(new URL("easy-mode-matrix.md",out),md);
const idolNone=[...new Set(rows.filter(r=>r.idol&&!r.easy_mode.length&&!r.excluded).map(r=>r.text||r.id))];
console.log(rows.length+" affixes, "+none.length+" gear lines without a group, "+exl.length+" excluded, "+idolNone.length+" idol lines without a group"+(idolNone.length?": "+idolNone.join("; "):""));
